const XRW = { key: "X-Requested-With", value: "XMLHttpRequest" };
const JSON_H = { key: "Content-Type", value: "application/json" };

function req(name, method, path, { body, headers = [XRW], tests = [], prerequest = [] } = {}) {
  return {
    name,
    event: [
      ...(prerequest.length
        ? [{ listen: "prerequest", script: { type: "text/javascript", exec: prerequest } }]
        : []),
      { listen: "test", script: { type: "text/javascript", exec: tests } },
    ],
    request: {
      method,
      header: body ? [...headers, JSON_H] : headers,
      url: `{{baseUrl}}${path}`,
      ...(body ? { body: { mode: "raw", raw: JSON.stringify(body, null, 2) } } : {}),
    },
  };
}

