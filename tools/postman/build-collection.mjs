#!/usr/bin/env node
// Builds the P0 API contract collection (Tech Design §14, §16; hackathon: P0 endpoints only, §1.1).
//   node tools/postman/build-collection.mjs  →  apps/api/postman/terrasight-p0.postman_collection.json
// Run: postman collection run apps/api/postman/terrasight-p0.postman_collection.json --env-var baseUrl=http://localhost:4000
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../apps/api/postman/terrasight-p0.postman_collection.json",
);

const XRW = { key: "X-Requested-With", value: "XMLHttpRequest" };
const JSON_H = { key: "Content-Type", value: "application/json" };

function req(name, method, path, { body, headers = [XRW], tests = [], prerequest = [] } = {}) {
  return {
    name,
    event: [
      ...(prerequest.length
        ? [{ listen: "prerequest", script: { type: "text/javascript", exec: prerequest } }]
        : []),
      { listen: "test", script: { type: "text/javascript", exec: tests } },
    ],
    request: {
      method,
      header: body ? [...headers, JSON_H] : headers,
      url: `{{baseUrl}}${path}`,
      ...(body ? { body: { mode: "raw", raw: JSON.stringify(body, null, 2) } } : {}),
    },
  };
}

const status = (code) => `pm.test("status ${code}", () => pm.response.to.have.status(${code}));`;
const problem = (code, type) => [
  status(code),
  `pm.test("problem+json", () => pm.expect(pm.response.headers.get("Content-Type")).to.include("application/problem+json"));`,
  ...(type
    ? [`pm.test("type ${type}", () => pm.expect(pm.response.json().type).to.include("${type}"));`]
    : []),
];

const collection = {
  info: {
    name: "Terrasight P0 contract",
    description:
      "Contract tests for P0 endpoints (Tech Design §14, §16). Generated by tools/postman/build-collection.mjs.",
    schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
  },
  variable: [{ key: "baseUrl", value: "http://localhost:4000" }],
  event: [
    {
      listen: "prerequest",
      script: {
        type: "text/javascript",
        exec: [
          "if (!pm.collectionVariables.get('run')) {",
          "  const run = Date.now().toString(36);",
          "  pm.collectionVariables.set('run', run);",
          "  pm.collectionVariables.set('ownerEmail', `owner-${run}@example.com`);",
          "  pm.collectionVariables.set('viewerEmail', `viewer-${run}@example.com`);",
          "}",
        ],
      },
    },
  ],
  item: [
    {
      name: "Auth (S-01.01)",
      item: [
        req("Sign up the owner", "POST", "/api/auth/signup", {
          body: {
            email: "{{ownerEmail}}",
            password: "correct horse battery",
            name: "Olena Koval",
            uiLanguage: "uk",
          },
          tests: [
            status(201),
            `pm.test("access + refresh cookies are httpOnly", () => {`,
            `  const set = pm.response.headers.filter((h) => h.key.toLowerCase() === "set-cookie").map((h) => h.value).join("\\n");`,
            `  pm.expect(set).to.match(/ts_at=[^;]+;.*HttpOnly/i);`,
            `  pm.expect(set).to.match(/ts_rt=[^;]+;.*Path=\\/api\\/auth.*HttpOnly/i);`,
            `  pm.expect(set).to.match(/SameSite=Lax/i);`,
            `});`,
            `pm.test("returns the user without workspaces", () => {`,
            `  const b = pm.response.json(); pm.expect(b.email).to.eql(pm.collectionVariables.get("ownerEmail"));`,
            `  pm.expect(b.workspaces).to.eql([]); pm.expect(b).to.not.have.property("passwordHash");`,
            `});`,
          ],
        }),
        req("Mutating request without X-Requested-With is refused (CSRF)", "POST", "/api/workspaces", {
          headers: [],
          body: { name: "x", timeZone: "UTC", units: "metric", reportLanguage: "en" },
          tests: problem(403, "csrf"),
        }),
        req("Same email cannot sign up twice", "POST", "/api/auth/signup", {
          body: { email: "{{ownerEmail}}", password: "another long password", name: "X" },
          tests: problem(409, "email-taken"),
        }),
        req("Short password is invalid", "POST", "/api/auth/signup", {
          body: { email: "short-{{run}}@example.com", password: "123", name: "X" },
          tests: [
            ...problem(422, "invalid-input"),
            `pm.test("names the field", () => pm.expect(pm.response.json().errors[0].path).to.eql("password"));`,
          ],
        }),
        req("Wrong password", "POST", "/api/auth/login", {
          body: { email: "{{ownerEmail}}", password: "wrong password!!" },
          tests: problem(401, "bad-credentials"),
        }),
        req("Sign in", "POST", "/api/auth/login", {
          body: { email: "{{ownerEmail}}", password: "correct horse battery" },
          tests: [status(200)],
        }),
        req("Me", "GET", "/api/me", {
          tests: [
            status(200),
            `pm.test("ui language kept", () => pm.expect(pm.response.json().uiLanguage).to.eql("uk"));`,
          ],
        }),
        req("Refresh rotates the session", "POST", "/api/auth/refresh", { tests: [status(204)] }),
      ],
    },
    {
      name: "Onboarding and workspace (S-01.02)",
      item: [
        req("Unknown time zone is invalid", "POST", "/api/workspaces", {
          body: {
            name: "Prairie Field Co.",
            timeZone: "Mars/Olympus",
            units: "imperial",
            reportLanguage: "en",
          },
          tests: problem(422, "invalid-input"),
        }),
        req("Create the company", "POST", "/api/workspaces", {
          body: {
            name: "Prairie Field Co.",
            timeZone: "America/Chicago",
            units: "imperial",
            reportLanguage: "en",
          },
          tests: [
            status(201),
            `const b = pm.response.json(); pm.collectionVariables.set("ws", b.id);`,
            `pm.test("creator is the Owner", () => pm.expect(b.role).to.eql("owner"));`,
            `pm.test("settings stored", () => { pm.expect(b.timeZone).to.eql("America/Chicago"); pm.expect(b.units).to.eql("imperial"); });`,
          ],
        }),
        req("Ukrainian time zone name is accepted", "POST", "/api/workspaces", {
          body: { name: "Агро Степ", timeZone: "Europe/Kyiv", units: "metric", reportLanguage: "uk" },
          tests: [status(201)],
        }),
        req("Read the workspace", "GET", "/api/w/{{ws}}", {
          tests: [
            status(200),
            `pm.test("no fields yet", () => pm.expect(pm.response.json().fieldCount).to.eql(0));`,
          ],
        }),
        req("Change settings", "PATCH", "/api/w/{{ws}}", {
          body: { reportLanguage: "uk" },
          tests: [status(200)],
        }),
        req(
          "Another workspace is not found (not forbidden)",
          "GET",
          "/api/w/00000000-0000-4000-8000-000000000000",
          { tests: problem(404) },
        ),
        req("Demo company before the seed", "POST", "/api/workspaces/demo-copy", {
          tests: problem(404, "demo-not-seeded"),
        }),
      ],
    },
    {
      name: "Invite the owner as a Viewer (S-01.03, S-01.04)",
      item: [
        req("Invite by email", "POST", "/api/w/{{ws}}/invitations", {
          body: { email: "{{viewerEmail}}", role: "viewer" },
          tests: [status(201), `pm.collectionVariables.set("inviteToken", pm.response.json().token);`],
        }),
        req("Phone numbers are not accepted", "POST", "/api/w/{{ws}}/invitations", {
          body: { email: "+1 620 555 0100" },
          tests: problem(422),
        }),
        req("Invitation info is public", "GET", "/api/invitations/{{inviteToken}}", {
          tests: [
            status(200),
            `pm.test("open, for the viewer", () => { const b = pm.response.json(); pm.expect(b.status).to.eql("open"); pm.expect(b.role).to.eql("viewer"); pm.expect(b.workspaceName).to.eql("Prairie Field Co."); });`,
          ],
        }),
        req("Sign out", "POST", "/api/auth/logout", { tests: [status(204)] }),
        req("Signed out: me is 401", "GET", "/api/me", { tests: problem(401) }),
        req("Sign up the invited viewer", "POST", "/api/auth/signup", {
          body: { email: "{{viewerEmail}}", password: "viewer long password", name: "John Miller" },
          tests: [status(201)],
        }),
        req("Accept the invitation", "POST", "/api/invitations/{{inviteToken}}/accept", {
          tests: [
            status(200),
            `pm.test("joined as viewer", () => pm.expect(pm.response.json().role).to.eql("viewer"));`,
          ],
        }),
        req("An invitation works once", "POST", "/api/invitations/{{inviteToken}}/accept", {
          tests: problem(410, "invitation-used"),
        }),
        req("Viewer can read the workspace", "GET", "/api/w/{{ws}}", {
          tests: [
            status(200),
            `pm.test("role viewer", () => pm.expect(pm.response.json().role).to.eql("viewer"));`,
          ],
        }),
        req("Viewer cannot change settings", "PATCH", "/api/w/{{ws}}", {
          body: { name: "Hacked" },
          tests: problem(403),
        }),
        req("Viewer cannot see members", "GET", "/api/w/{{ws}}/members", { tests: problem(403) }),
        req("Viewer cannot invite", "POST", "/api/w/{{ws}}/invitations", {
          body: { email: "x-{{run}}@example.com" },
          tests: problem(403),
        }),
        req("Viewer can open the event stream topic list (read)", "GET", "/api/w/{{ws}}/events?topics=nope", {
          tests: problem(400),
        }),
      ],
    },
    {
      name: "Owner manages members (S-01.04)",
      item: [
        req("Owner signs back in", "POST", "/api/auth/login", {
          body: { email: "{{ownerEmail}}", password: "correct horse battery" },
          tests: [status(200)],
        }),
        req("Members list", "GET", "/api/w/{{ws}}/members", {
          tests: [
            status(200),
            `const m = pm.response.json().members; pm.test("owner + viewer", () => pm.expect(m.map((x) => x.role).sort()).to.eql(["owner", "viewer"]));`,
            `pm.collectionVariables.set("ownerId", m.find((x) => x.role === "owner").id);`,
            `pm.collectionVariables.set("viewerId", m.find((x) => x.role === "viewer").id);`,
          ],
        }),
        req("The last Owner cannot step down", "PATCH", "/api/w/{{ws}}/members/{{ownerId}}", {
          body: { role: "admin" },
          tests: problem(409, "last-owner"),
        }),
        req("Promote the viewer to agronomist", "PATCH", "/api/w/{{ws}}/members/{{viewerId}}", {
          body: { role: "agronomist" },
          tests: [status(200)],
        }),
        req("Remove the member", "DELETE", "/api/w/{{ws}}/members/{{viewerId}}", { tests: [status(204)] }),
      ],
    },
  ],
};

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify(collection, null, 2) + "\n");
const count = collection.item.reduce((n, g) => n + g.item.length, 0);
console.log(`wrote ${out} (${count} requests)`);
